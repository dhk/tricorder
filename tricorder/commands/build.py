"""
tricorder build — generate the interactive explorer from .tricorder/ artifacts

Reads learnings.json (Level 3) and writes explorer/data.js so the static
HTML explorer reflects the current analysis.

Optionally applies a name map from ~/.tricorder/<owner>__<repo>-name-map.json.

Usage:
  tricorder build                          # infers repo from git remote
  tricorder build OWNER/REPO
  tricorder build --out PATH/data.js       # custom output path
  tricorder build --name-map PATH          # explicit name map
  tricorder build --open                   # open explorer in browser after build
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import webbrowser
from datetime import datetime
from pathlib import Path


# ---------------------------------------------------------------------------
# Category / radar constants (must match explorer app)
# ---------------------------------------------------------------------------

CATEGORIES = [
    "grain", "naming", "testing", "documentation", "style",
    "performance", "modeling", "schema", "business-logic",
    # extended for non-analytics lenses
    "structure", "security", "other",
]

CATEGORY_GROUP = {
    "grain": "data", "naming": "pattern", "testing": "tool",
    "documentation": "pattern", "style": "pattern", "performance": "data",
    "modeling": "data", "schema": "data", "business-logic": "pattern",
    "structure": "pattern", "security": "tool", "other": "pattern",
}

CATEGORY_KEYWORDS = {
    "grain":          ["grain", "dedup", "fanout", "granularity", "row count"],
    "naming":         ["naming", "convention", "snake_case", "prefix", "stg_", "fct_", "dim_"],
    "testing":        ["test", "uniqueness", "not_null", "referential", "primary key", "coverage"],
    "documentation":  ["documentation", "docs", "description", "comment", "schema.yml", "readme"],
    "style":          ["style", "cte", "readability", "formatting", "alias", "select *"],
    "performance":    ["performance", "cost", "partition", "clustering", "scan", "expensive"],
    "modeling":       ["incremental", "materialization", "staging", "mart", "intermediate", "scd"],
    "schema":         ["source freshness", "schema change", "breaking change", "freshness", "contract"],
    "business-logic": ["business logic", "domain", "derived field", "conditional", "spec"],
    "structure":      ["structure", "folder", "organization", "module", "layer", "layout"],
    "security":       ["security", "auth", "permission", "injection", "secret", "credential", "xss"],
    "other":          [],
}

FREQ_MAP = {"always": 90, "often": 70, "sometimes": 45, "rarely": 22, "never": 5}
BASELINE = 8


def taxonomy_from_lens(lens) -> dict:
    """Categories, colour groups, radar axes, and keyword map derived from a Lens."""
    cats = lens.category_ids
    groups = {c: lens.category_group(c) for c in cats}
    radar = [c for c in lens.core_category_ids if c != "other"] or [c for c in cats if c != "other"][:9]
    keywords: dict[str, list[str]] = {}
    for c in lens.categories:
        kws = list(c.get("keywords") or [])
        kws.append(c["id"].replace("-", " "))
        kws += CATEGORY_KEYWORDS.get(c["id"], [])
        keywords[c["id"]] = sorted(set(k for k in kws if k))
    return {"categories": cats, "groups": groups, "radar": radar, "keywords": keywords,
            "lens": lens.summary()}


def _taxonomy_for(learnings: dict) -> dict:
    """Lens-driven taxonomy when the learnings name a lens; legacy dbt set otherwise."""
    info = learnings.get("lens") or {}
    name = info.get("name")
    if name:
        try:
            from tricorder.lenses import load_lens
            tax = taxonomy_from_lens(load_lens(name))
            tax["lens"] = {**tax["lens"], **{k: v for k, v in info.items() if k not in tax["lens"]}}
            return tax
        except Exception as e:  # lens missing on this machine: fall back but say so
            print(f"  ⚠ lens {name!r} not loadable ({e}); falling back to the legacy category set")
    cats = [c for c in CATEGORIES if c in CATEGORY_GROUP or c == "other"]
    return {"categories": cats, "groups": CATEGORY_GROUP,
            "radar": [c for c in cats if c != "other"][:9], "keywords": CATEGORY_KEYWORDS,
            "lens": info or None}


JS_TEMPLATE = """\
// Generated by tricorder build — {generated}
// Repo: {repo}  |  Version: {version}
window.TRICORDER_DATA = (function () {{

  const CATEGORIES = {categories};
  const RADAR_CATEGORIES = {radar_categories};
  const CATEGORY_GROUP = {category_group};
  const lens = {lens_js};

  const patterns = {patterns};

  const reviewers = {reviewers};

  const authors = {authors};

  const gaps = {gaps};

  return {{
    repo:             {repo_js},
    window:           {window_js},
    pr_count:         {pr_count},
    prs_with_reviews: {prs_with_reviews},
    contributors:     {contributors},
    visibility:       {visibility_js},
    version:          {version_js},
    lens,
    CATEGORIES,
    RADAR_CATEGORIES,
    CATEGORY_GROUP,
    patterns,
    reviewers,
    authors,
    gaps,
  }};
}})();
"""


# ---------------------------------------------------------------------------
# Name map
# ---------------------------------------------------------------------------

def _load_name_map(repo: str, explicit_path: str | None) -> dict:
    if explicit_path:
        p = Path(explicit_path).expanduser()
        if p.exists():
            return json.loads(p.read_text())
        print(f"  Name map not found at {p} — proceeding without.", file=sys.stderr)
        return {}

    slug = repo.replace("/", "__")
    auto = Path.home() / ".tricorder" / f"{slug}-name-map.json"
    if auto.exists():
        print(f"  Name map: {auto}")
        return json.loads(auto.read_text())
    return {}


def _apply_map(obj, name_map: dict):
    if not name_map:
        return obj
    if isinstance(obj, str):
        return name_map.get(obj, obj)
    if isinstance(obj, list):
        return [_apply_map(i, name_map) for i in obj]
    if isinstance(obj, dict):
        return {k: _apply_map(v, name_map) for k, v in obj.items()}
    return obj


# ---------------------------------------------------------------------------
# Radar / category inference
# ---------------------------------------------------------------------------

def _infer_category_freq(focus_areas: list, categories: list | None = None,
                         keywords: dict | None = None) -> dict:
    categories = categories or CATEGORIES
    keyword_map = keywords or CATEGORY_KEYWORDS
    scores = {cat: BASELINE for cat in categories}
    for fa in focus_areas:
        text = ((fa.get("area") or "") + " " + (fa.get("category") or "") + " "
                + (fa.get("standard_citation") or "")).lower()
        freq_val = FREQ_MAP.get(fa.get("frequency", "sometimes"), 45)
        # a lens-aware Phase 2 tags each focus area with a category directly
        if fa.get("category") in scores:
            scores[fa["category"]] = max(scores[fa["category"]], freq_val)
        for cat, kws in keyword_map.items():
            if cat in scores and any(kw in text for kw in kws):
                scores[cat] = max(scores[cat], freq_val)
    return scores


